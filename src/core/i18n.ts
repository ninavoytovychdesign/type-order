export const DICTS: Record<Lang, Record<string, Entry>> = { en, uk }

export function pluralIndex(lang: Lang, n: number): number {
  if (lang === 'en') return n === 1 ? 0 : 1
  const m10 = n % 10
  const m100 = n % 100
  if (m10 === 1 && m100 !== 11) return 0
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 1
  return 2
}

/** Переклад з підстановкою {параметрів}; для форм множини потрібен параметр n. */
export function translate(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  const e = DICTS[lang][key] ?? DICTS.en[key]
  if (e === undefined) return key
  let s: string
  if (Array.isArray(e)) {
    const n = typeof params.n === 'number' ? params.n : Number(params.n) || 0
    s = e[Math.min(pluralIndex(lang, Math.abs(Math.trunc(n))), e.length - 1)]
  } else s = e
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (params[k] !== undefined ? String(params[k]) : `{${k}}`))
}
